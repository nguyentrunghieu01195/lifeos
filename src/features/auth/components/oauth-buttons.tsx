import { Button } from "@/components/ui/button";
import type { OAuthProviderId } from "@/lib/auth";

import { signInWithProviderAction } from "../server/actions";

/**
 * OAuth sign-in buttons — rendered only for providers whose credentials are
 * configured (the page passes the available list from the server).
 */
export function OAuthButtons({ providers }: { providers: OAuthProviderId[] }) {
  if (providers.length === 0) return null;

  return (
    <div className="grid gap-2">
      {providers.includes("google") ? (
        <form action={signInWithProviderAction.bind(null, "google")}>
          <Button type="submit" variant="outline" className="w-full">
            <GoogleIcon />
            Continue with Google
          </Button>
        </form>
      ) : null}
      {providers.includes("github") ? (
        <form action={signInWithProviderAction.bind(null, "github")}>
          <Button type="submit" variant="outline" className="w-full">
            <GitHubIcon />
            Continue with GitHub
          </Button>
        </form>
      ) : null}
    </div>
  );
}

